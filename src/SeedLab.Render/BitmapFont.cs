            string[] packed = new string[g.Length];
            for (int i = 0; i < g.Length; i++)
            {
                string[] rows = g[i];
                if (rows.Length != GlyphHeight)
                {
                    throw new InvalidOperationException($"Glyph {(char)(32 + i)} has {rows.Length} rows, expected {GlyphHeight}.");
                }

                System.Text.StringBuilder sb = new System.Text.StringBuilder(GlyphWidth * GlyphHeight);
                foreach (string r in rows)
                {
                    if (r.Length != GlyphWidth)
                    {
                        throw new InvalidOperationException($"Glyph {(char)(32 + i)} row '{r}' is {r.Length} wide, expected {GlyphWidth}.");
                    }

                    sb.Append(r);
                }

                packed[i] = sb.ToString();
            }

            return packed;
        }

        /// <summary>True when the glyph for <paramref name="c"/> has ink at (col, row).</summary>
        public static bool Pixel(char c, int col, int row)
        {
            int i = c - 32;
            if (i < 0 || i >= Glyphs.Length) i = '?' - 32;
            return Glyphs[i][row * GlyphWidth + col] == '#';
        }

        public static int MeasureWidth(string text, int scale)
            => text.Length == 0 ? 0 : (text.Length * Advance - 1) * scale;

        public static int LineHeight(int scale) => GlyphHeight * scale;

        /// <summary>Every glyph rendered as text, for eyeballing the table during development.</summary>
        public static IEnumerable<string> Proof(string text)
        {
            for (int row = 0; row < GlyphHeight; row++)
            {
                System.Text.StringBuilder sb = new System.Text.StringBuilder();
                foreach (char c in text)
                {
                    for (int col = 0; col < GlyphWidth; col++) sb.Append(Pixel(c, col, row) ? '#' : '.');
                    sb.Append(' ');
                }

                yield return sb.ToString();
            }
        }
    }
